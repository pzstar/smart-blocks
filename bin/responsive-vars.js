/**
 * Generates the tablet and mobile rules for responsive variables.
 *
 * A responsive control stores three variables: --sb-<name>-lg, -md and -sm.
 * In sb-style.css only the desktop rule is written by hand:
 *
 *     .sb-block-title { font-size: var(--sb-header-typo-fs-lg, 20px); }
 *
 * This script finds every declaration that reads a "-lg" variable and writes
 * the matching tablet and mobile rules, with the same selector, into the next
 * "Responsive variables" section of the file:
 *
 *     @media (max-width:1024px) { ... var(--sb-header-typo-fs-md, var(--sb-header-typo-fs-lg, 20px)) }
 *     @media (max-width:767px)  { ... var(--sb-header-typo-fs-sm, var(--sb-header-typo-fs-md, var(--sb-header-typo-fs-lg, 20px))) }
 *
 * A section covers the hand written rules between the previous section (or the
 * top of the file) and itself, so it always sits after the desktop rules it
 * mirrors and before the hand written media queries that follow it. To start a
 * new section, add the two marker comments below where it should go.
 *
 * `npm run build` runs this, so adding a responsive style only takes the
 * desktop rule.
 */
const fs = require('fs');
const path = require('path');

const cssFile = path.resolve(__dirname, '../inc/assets/css/sb-style.css');
const start = '/* Responsive variables: generated by bin/responsive-vars.js from the rules above, do not edit by hand */';
const end = '/* End of responsive variables */';

const fail = (message) => {
  console.error('responsive-vars: ' + message);
  process.exit(1);
};

/**
 * Returns the top level rules of a piece of CSS: [{selector, declarations}].
 * At-rules (media queries, font faces) are skipped as a whole.
 */
const readRules = (css) => {
  const rules = [];
  let depth = 0;
  let blockStart = 0;
  let prelude = '';
  let last = 0;

  css = css.replace(/\/\*[\s\S]*?\*\//g, (comment) => ' '.repeat(comment.length));

  for (let i = 0; i < css.length; i++) {
    if ('{' === css[i]) {
      if (0 === depth) {
        prelude = css.slice(last, i).trim();
        blockStart = i + 1;
      }
      depth++;
    } else if ('}' === css[i]) {
      depth--;
      if (0 === depth) {
        if (prelude && '@' !== prelude[0]) {
          rules.push({selector: prelude, declarations: readDeclarations(css.slice(blockStart, i))});
        }
        last = i + 1;
      }
    }
  }

  return rules;
};

// Splits "a: b; c: d" on the semicolons that are not inside brackets.
const readDeclarations = (body) => {
  const declarations = [];
  let depth = 0;
  let from = 0;

  for (let i = 0; i <= body.length; i++) {
    const char = body[i];
    if ('(' === char) {
      depth++;
    } else if (')' === char) {
      depth--;
    } else if ((';' === char && 0 === depth) || i === body.length) {
      const text = body.slice(from, i).trim();
      const colon = text.indexOf(':');
      if (colon > 0) {
        declarations.push({property: text.slice(0, colon).trim(), value: text.slice(colon + 1).trim()});
      }
      from = i + 1;
    }
  }

  return declarations;
};

/**
 * Rewrites every var(--sb-<name>-lg ...) in a value for a smaller screen.
 *
 * @param {string}   value Declaration value.
 * @param {string[]} sizes Sizes to try first, e.g. ['md'] or ['sm', 'md'].
 * @return {string|null} Null when the value reads no "-lg" variable.
 */
const forScreen = (value, sizes) => {
  const pattern = /var\(\s*(--sb-[a-z0-9-]+)-lg\b/g;
  let out = '';
  let cursor = 0;
  let match;
  let found = false;

  while ((match = pattern.exec(value))) {
    // Find the bracket that closes this var().
    let depth = 0;
    let close = -1;
    for (let i = match.index; i < value.length; i++) {
      if ('(' === value[i]) {
        depth++;
      } else if (')' === value[i] && 0 === --depth) {
        close = i;
        break;
      }
    }
    if (-1 === close) {
      fail(`unbalanced brackets in "${value}"`);
    }

    // The fallback, if any, may itself read "-lg" variables.
    const inner = value.slice(match.index + match[0].length, close);
    const original = `var(${match[1]}-lg${forScreen(inner, sizes) || inner})`;

    out += value.slice(cursor, match.index) + sizes.reduceRight((fallback, size) => `var(${match[1]}-${size}, ${fallback})`, original);
    cursor = close + 1;
    pattern.lastIndex = cursor;
    found = true;
  }

  return found ? out + value.slice(cursor) : null;
};

const mediaBlock = (query, rules, sizes) => {
  const blocks = [];

  for (const rule of rules) {
    const lines = [];
    for (const {property, value} of rule.declarations) {
      const responsive = forScreen(value, sizes);
      if (null !== responsive) {
        lines.push(`        ${property}: ${responsive};`);
      }
    }
    if (lines.length) {
      const selector = rule.selector.split(/,\s*/).map((part) => '    ' + part.trim()).join(',\n');
      blocks.push(`${selector} {\n${lines.join('\n')}\n    }`);
    }
  }

  return blocks.length ? `@media screen and (${query}) {\n${blocks.join('\n\n')}\n}` : '';
};

let css = fs.readFileSync(cssFile, 'utf8');
let cursor = 0;
let out = '';
let sections = 0;
let written = 0;

for (;;) {
  const from = css.indexOf(start, cursor);
  if (-1 === from) {
    break;
  }
  const to = css.indexOf(end, from);
  if (-1 === to) {
    fail('a section has no end marker.');
  }

  const handWritten = css.slice(cursor, from);
  const rules = readRules(handWritten);
  const tablet = mediaBlock('max-width:1024px', rules, ['md']);
  const mobile = mediaBlock('max-width:767px', rules, ['sm', 'md']);

  written += (tablet.match(/var\(--sb-[a-z0-9-]+-md, var\(/g) || []).length;
  out += handWritten + [start, tablet, mobile, end].filter(Boolean).join('\n\n');
  cursor = to + end.length;
  sections++;
}

if (!sections) {
  fail('no "Responsive variables" section found in sb-style.css.');
}

fs.writeFileSync(cssFile, out + css.slice(cursor));
console.log(`responsive-vars: ${sections} sections, ${written} responsive values per screen size written.`);
